#!/usr/bin/env node
/**
 * No-loss guard (Dorin's standing rule, 10 Oct 2026: nothing on mrwallcover.com may be lost).
 *
 *   node scripts/no-loss-guard.mjs --base-dist <main build> [--dist dist] [--base-ref origin/main] [--json report.json]
 *
 * Compares this branch with origin/main and exits 1 when anything published would be lost:
 *  (a) a URL in main's sitemap is missing from this build's sitemap;
 *  (b) a case study disappears, is unpublished (draft), or its gallery frame count drops; a project
 *      record in src/content/projects.json disappears, or its gallery or film count drops;
 *  (c) a file under public/media (or an image at the top of public/) is deleted without a
 *      replacement: the same base name or slot (base name minus a -800 / -1600w / -preview size
 *      suffix), in any format, with pixel dimensions at least as large. Reorders are allowed;
 *  (d) the Lee Broom case study or any project card that main lists on /projects/ or the home
 *      page is missing;
 *  (e) the AI layer shrinks: /for-ai/, /llms.txt, /llms-full.txt, /facts.json, /.well-known/*,
 *      /feed.xml, every Markdown twin, /wallcovering-installation-ai-crawler/ and /ai/*.json must
 *      all still exist with no lower count (JSON leaves and array entries, text lines and links,
 *      feed items, list items and links on HTML pages); robots.txt keeps every User-agent/Allow
 *      line; and no page has fewer JSON-LD nodes or properties than on main;
 *  (f) the homepage has fewer sections, section headings, linked case studies or photographs
 *      than the homepage at 1b387c6 (the last one before #23), drops a case study that page
 *      linked, or loses Lee Broom. The 1b387c6 counts are committed in
 *      scripts/home-baseline-1b387c6.json, generated by scripts/home-counts.mjs from a build.
 *      Owner-authorised concise homepages instead require the full immutable published-content
 *      inventory to survive in indexable main content, plus seven or eight homepage sections.
 *      Only proven relocation permits the corresponding homepage/aggregate count reductions.
 *
 * The baseline is never a hand-kept list: (a), (d) and (e) read main's own build (CI builds
 * origin/main in a worktree), and (b) and (c) read main's committed files with git.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { homeCounts } from './home-counts.mjs';
import { publishedHomeInventory, verifyHomePreservation } from './home-preservation.mjs';

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : fallback;
};
const root = path.resolve(import.meta.dirname, '..');
const baseDist = opt('base-dist');
const dist = path.resolve(root, opt('dist', 'dist'));
const baseRef = opt('base-ref', 'origin/main');
const jsonOut = opt('json');
if (!baseDist) {
  console.error('Usage: node scripts/no-loss-guard.mjs --base-dist <main build> [--dist dist] [--base-ref origin/main]');
  process.exit(2);
}
const base = path.resolve(baseDist);

const failures = [];
const fail = (check, message) => failures.push(`(${check}) ${message}`);
const report = { baseRef, counts: { base: {}, pr: {} }, galleries: {}, ai: {} };

const git = (...a) => execFileSync('git', a, { cwd: root, encoding: 'buffer', maxBuffer: 1 << 28 });
const gitText = (...a) => git(...a).toString('utf8');

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}
const rel = (dir, file) => path.relative(dir, file).split(path.sep).join('/');
const read = (dir, file) => readFileSync(path.join(dir, file), 'utf8');
const has = (dir, file) => existsSync(path.join(dir, file));

// On 19 October the owner explicitly requested a shorter homepage, with its
// complete content moved to appropriate public pages. The fixed public inventory
// is verified against indexable main content before any count exception applies.
const conciseHome = has(dist, 'index.html') && /data-home-composition="concise"/.test(read(dist, 'index.html'));
let homeRelocation = null;
if (conciseHome) {
  const inventory = JSON.parse(readFileSync(path.join(root, 'scripts/home-content-preservation-2026-10-19.json'), 'utf8'));
  homeRelocation = await verifyHomePreservation(dist, inventory);
  report.homeRelocation = homeRelocation;
  // Also preserve the actual current baseline, so later PRs cannot rely only on
  // the initial relocation inventory to discard subsequently published home copy.
  const currentMainHome = await verifyHomePreservation(dist, publishedHomeInventory(read(base,'index.html'),baseRef));
  report.currentMainHome = currentMainHome;
  for (const missing of currentMainHome.missing) fail('current home relocation', `${missing.kind} missing from indexable main content: ${JSON.stringify(missing.value)}`);
  homeRelocation.passed = homeRelocation.passed && currentMainHome.passed;
  for (const missing of homeRelocation.missing) fail('home relocation', `${missing.kind} missing from published main content: ${JSON.stringify(missing.value)}`);
}
const relocated = conciseHome && homeRelocation?.passed;

// Owner-held pages (Dorin, 22 Oct 2026: Wallpaper My Room stays hidden until its tools finish
// testing). A held page is not lost: it must still be built, at the same URL, and carry
// noindex. Only its own sitemap entry, Markdown twin and AI page record may then be absent,
// because noindex pages are excluded from the sitemap and the AI layer by design.
const HELD_PAGES = ['/room-studio/'];
const heldPage = new Set();
for (const held of HELD_PAGES) {
  const file = `${held.slice(1)}index.html`;
  if (!has(dist, file)) { fail('held', `${held} must still be built`); continue; }
  if (!/<meta name="robots" content="noindex/.test(read(dist, file))) { fail('held', `${held} is held but not noindex`); continue; }
  heldPage.add(held);
}
const isHeldUrl = (u) => { try { return heldPage.has(new URL(u, 'https://www.mrwallcover.com').pathname); } catch { return false; } };

// (a) Sitemap URLs.
function sitemapUrls(dir) {
  const urls = new Set();
  for (const f of readdirSync(dir).filter((n) => /^sitemap-\d+\.xml$/.test(n))) {
    for (const m of read(dir, f).matchAll(/<loc>([^<]+)<\/loc>/g)) urls.add(m[1].trim());
  }
  return urls;
}
const baseUrls = sitemapUrls(base);
const prUrls = sitemapUrls(dist);
report.counts.base.pages = baseUrls.size;
report.counts.pr.pages = prUrls.size;
for (const u of baseUrls) if (!prUrls.has(u) && !isHeldUrl(u)) fail('a', `sitemap URL missing: ${u}`);

// (b) Case studies and gallery frames, from main's committed files.
const csDir = 'src/content/case-studies';
function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  return m ? JSON.parse(m[1]) : {};
}
const baseStudies = gitText('ls-tree', '--name-only', `${baseRef}:${csDir}`).split('\n').filter((n) => n.endsWith('.md'));
for (const name of baseStudies) {
  const b = frontmatter(gitText('show', `${baseRef}:${csDir}/${name}`));
  const prPath = path.join(root, csDir, name);
  const slug = b.slug ?? name.replace(/\.md$/, '');
  const bFrames = (b.gallery ?? []).length;
  if (!existsSync(prPath)) {
    fail('b', `case study removed: ${csDir}/${name}`);
    report.galleries[slug] = { base: bFrames, pr: null };
    continue;
  }
  const p = frontmatter(readFileSync(prPath, 'utf8'));
  const pFrames = (p.gallery ?? []).length;
  report.galleries[slug] = { base: bFrames, pr: pFrames, draft: { base: !!b.draft, pr: !!p.draft } };
  if (pFrames < bFrames) fail('b', `${slug}: gallery frames dropped from ${bFrames} to ${pFrames}`);
  if (!b.draft && p.draft) fail('b', `${slug}: published on main, set to draft here`);
}

// (b2) The project records in src/content/projects.json carry their own gallery and film lists
// (they feed /projects/, the project pages and the AI layer). A record may not disappear, and its
// gallery or film count may not drop. Reorders and swaps of the same count are allowed.
const projectsFile = 'src/content/projects.json';
const projectItems = (text) => {
  const data = JSON.parse(text);
  return new Map((Array.isArray(data) ? data : data.items ?? []).map((item) => [item.slug, item]));
};
const baseProjects = projectItems(gitText('show', `${baseRef}:${projectsFile}`));
const prProjects = projectItems(readFileSync(path.join(root, projectsFile), 'utf8'));
report.projects = {};
for (const [slug, b] of baseProjects) {
  const p = prProjects.get(slug);
  const bG = (b.gallery ?? []).length, bV = (b.videos ?? []).length;
  if (!p) {
    fail('b', `${projectsFile}: project record removed: ${slug}`);
    report.projects[slug] = { gallery: { base: bG, pr: null } };
    continue;
  }
  const pG = (p.gallery ?? []).length, pV = (p.videos ?? []).length;
  report.projects[slug] = { gallery: { base: bG, pr: pG }, videos: { base: bV, pr: pV } };
  if (pG < bG) fail('b', `${projectsFile}: ${slug} gallery entries dropped from ${bG} to ${pG}`);
  if (pV < bV) fail('b', `${projectsFile}: ${slug} films dropped from ${bV} to ${pV}`);
}
const sum = (m, k) => [...m.values()].reduce((n, item) => n + (item[k] ?? []).length, 0);
report.counts.base.projectRecords = baseProjects.size;
report.counts.pr.projectRecords = prProjects.size;
report.counts.base.projectGalleryEntries = sum(baseProjects, 'gallery');
report.counts.pr.projectGalleryEntries = sum(prProjects, 'gallery');

// (c) Media files: deleted only with an equal-or-larger replacement of the same shot.
const MEDIA = /^public\/(media\/.+|[^/]+\.(jpe?g|png|webp|avif|gif|svg))$/i;
const IMAGE = /\.(jpe?g|png|webp|avif|gif|tiff?)$/i;
const baseMedia = gitText('ls-tree', '-r', '--name-only', baseRef, '--', 'public').split('\n').filter((f) => MEDIA.test(f));
const prMedia = walk(path.join(root, 'public')).map((f) => rel(root, f)).filter((f) => MEDIA.test(f));
report.counts.base.mediaFiles = baseMedia.length;
report.counts.pr.mediaFiles = prMedia.length;
report.counts.base.imageFiles = baseMedia.filter((f) => IMAGE.test(f)).length;
report.counts.pr.imageFiles = prMedia.filter((f) => IMAGE.test(f)).length;
const prSet = new Set(prMedia);
const stem = (f) => path.basename(f).replace(/\.[^.]+$/, '');
const slot = (f) => stem(f).replace(/-(?:\d{2,5}w?|preview|thumb)$/i, '');
const bySlot = new Map();
for (const f of prMedia) {
  for (const key of new Set([stem(f), slot(f)])) {
    if (!bySlot.has(key)) bySlot.set(key, []);
    bySlot.get(key).push(f);
  }
}
async function dims(input) {
  try {
    const m = await sharp(input).metadata();
    return m.width && m.height ? { w: m.width, h: m.height } : null;
  } catch {
    return null;
  }
}
for (const f of baseMedia) {
  if (prSet.has(f)) continue;
  const candidates = [...new Set([...(bySlot.get(stem(f)) ?? []), ...(bySlot.get(slot(f)) ?? [])])];
  if (!candidates.length) {
    fail('c', `media deleted with no replacement: ${f}`);
    continue;
  }
  if (!IMAGE.test(f)) continue; // a video or other file: the same base name in any format is enough
  const was = await dims(git('show', `${baseRef}:${f}`));
  if (!was) continue;
  let ok = false;
  for (const c of candidates) {
    const now = await dims(path.join(root, c));
    if (now && now.w >= was.w && now.h >= was.h) { ok = true; break; }
  }
  if (!ok) fail('c', `media deleted and only replaced at a smaller size: ${f} (${was.w}x${was.h}); candidates ${candidates.join(', ')}`);
}

// (d) Lee Broom, and every project card main lists on /projects/ and the home page.
const LEE = 'calico-lee-broom-overture';
const leePage = `projects/${LEE}/index.html`;
if (!has(dist, leePage)) fail('d', `Lee Broom case study page missing: /${leePage.replace('index.html', '')}`);
else if (/<meta name="robots" content="noindex/.test(read(dist, leePage))) fail('d', 'Lee Broom case study is noindex');
if (!has(dist, 'projects/index.html') || !read(dist, 'projects/index.html').includes(`data-project-slug="${LEE}"`)) fail('d', 'Lee Broom card missing from /projects/');
if (!prUrls.has(`https://www.mrwallcover.com/projects/${LEE}/`)) fail('d', 'Lee Broom page missing from the sitemap');
const cardSlugs = (html) => new Set([...html.matchAll(/data-project-slug="([^"]+)"/g)].map((m) => m[1]));
const projectLinks = (html) => new Set([...html.matchAll(/href="\/projects\/([a-z0-9-]+)\/"/g)].map((m) => m[1]));
for (const [page, extract] of [['projects/index.html', cardSlugs], ['projects/index.html', projectLinks], ['index.html', projectLinks]]) {
  if (!has(base, page)) continue;
  const before = extract(read(base, page));
  const after = has(dist, page) ? extract(read(dist, page)) : new Set();
  for (const s of before) if (!after.has(s)) {
    const moved = page === 'index.html' && relocated && homeRelocation.locations.some(item => item.kind === 'public link' && item.value === `/projects/${s}/`);
    if (!moved) fail('d', `/${page.replace('index.html', '')}: project card or link to /projects/${s}/ missing`);
  }
}

// (e) AI layer.
function leaves(v) {
  if (Array.isArray(v)) return v.reduce((n, x) => n + leaves(x), 0);
  if (v && typeof v === 'object') return Object.values(v).reduce((n, x) => n + leaves(x), 0);
  return 1;
}
function maxArray(v) {
  if (Array.isArray(v)) return Math.max(v.length, ...v.map(maxArray));
  if (v && typeof v === 'object') return Math.max(0, ...Object.values(v).map(maxArray));
  return 0;
}
const textMeasures = (t) => ({ lines: t.split('\n').filter((l) => l.trim()).length, links: (t.match(/\]\([^)]+\)|https?:\/\/\S+/g) ?? []).length });
const htmlMain = (t) => (t.match(/<main[\s\S]*?<\/main>/) ?? [t])[0];
const htmlMeasures = (t) => ({ listItems: (htmlMain(t).match(/<li[\s>]/g) ?? []).length, links: (htmlMain(t).match(/<a\s[^>]*href=/g) ?? []).length });
function measure(dir, file) {
  const t = read(dir, file);
  if (file.endsWith('.json')) {
    const d = JSON.parse(t);
    // A held page's own record leaves the AI page manifests with its noindex; compare the rest.
    if (/^ai\/[^/]+\.json$/.test(file) && d && Array.isArray(d.pages)) d.pages = d.pages.filter((page) => !(page && heldPage.has(page.path)));
    // Top-level lists by name (e.g. /ai/projects.json "projects", the 16-project dataset).
    const entries = Object.fromEntries(Object.entries(d && !Array.isArray(d) ? d : {}).filter(([, v]) => Array.isArray(v)).map(([k, v]) => [`entries.${k}`, v.length]));
    return { jsonLeaves: leaves(d), largestList: maxArray(d), ...(Array.isArray(d) ? { entries: d.length } : entries) };
  }
  if (file.endsWith('.xml')) return { items: (t.match(/<item[\s>]|<entry[\s>]/g) ?? []).length };
  if (file.endsWith('.html')) return htmlMeasures(t);
  return textMeasures(t);
}
const baseFiles = walk(base).map((f) => rel(base, f));
const aiFiles = baseFiles.filter((f) =>
  ['for-ai/index.html', 'llms.txt', 'llms-full.txt', 'facts.json', 'feed.xml', 'wallcovering-installation-ai-crawler/index.html'].includes(f) ||
  f.startsWith('.well-known/') || /^ai\/[^/]+\.json$/.test(f) || f.endsWith('.md'));
report.counts.base.markdownTwins = baseFiles.filter((f) => f.endsWith('.md')).length;
report.counts.pr.markdownTwins = walk(dist).filter((f) => f.endsWith('.md')).length;
for (const f of aiFiles) {
  if (!has(dist, f)) { if (!(f.endsWith('index.md') && heldPage.has(`/${f.replace(/index\.md$/, '')}`))) fail('e', `AI layer file missing: /${f}`); continue; }
  const b = measure(base, f);
  const p = measure(dist, f);
  if (!f.endsWith('.md') || f.startsWith('wallcovering-installation-ai-crawler/')) report.ai[f] = { base: b, pr: p };
  // These two prose projections must follow the concise page and the relocated
  // corpus. A repeated paragraph need not be duplicated just to keep line counts.
  const relocatedProse = relocated && ['index.md', 'llms-full.txt'].includes(f);
  // Removing a generic study also removes its enhancement-only labels from the
  // Guide projection. Require every substantive baseline line to survive exactly.
  const guidePresentationOnly = f === 'advice/index.md' && read(base,f).split('\n')
    .map(line=>line.trim()).filter(line=>line && !['Illustrative study','Pause motion'].includes(line))
    .every(line=>read(dist,f).split('\n').map(value=>value.trim()).includes(line));
  if (guidePresentationOnly) report.ai[f] = {base:b,pr:p,substantiveLinesPreserved:true,removedEnhancementLabels:['Illustrative study','Pause motion']};
  for (const k of Object.keys(b)) if ((p[k] ?? 0) < b[k] && !relocatedProse && !(guidePresentationOnly && k === 'lines')) fail('e', `/${f}: ${k} dropped from ${b[k]} to ${p[k] ?? 0}`);
}
// robots.txt: every User-agent / Allow line on main stays, in the same group.
function robotGroups(t) {
  const out = new Set();
  let agents = [];
  let inRules = false;
  for (const line of t.split('\n').map((l) => l.replace(/#.*/, '').trim()).filter(Boolean)) {
    const [k, ...v] = line.split(':');
    const key = k.trim().toLowerCase();
    const val = v.join(':').trim();
    if (key === 'user-agent') { if (inRules) { agents = []; inRules = false; } agents.push(val); }
    else { inRules = true; if (key === 'allow') for (const a of agents) out.add(`${a} Allow ${val}`); }
  }
  return out;
}
if (has(base, 'robots.txt')) {
  const b = robotGroups(read(base, 'robots.txt'));
  const p = has(dist, 'robots.txt') ? robotGroups(read(dist, 'robots.txt')) : new Set();
  report.ai['robots.txt'] = { base: { allowLines: b.size }, pr: { allowLines: p.size } };
  for (const line of b) if (!p.has(line)) fail('e', `robots.txt lost "${line}"`);
}
// JSON-LD node and property counts per page.
function ldCounts(html, omitFaq = false) {
  let nodes = 0, props = 0;
  const visit = (v) => {
    if (Array.isArray(v)) return v.forEach(visit);
    if (v && typeof v === 'object') {
      if (omitFaq && v['@type'] === 'FAQPage') return;
      if ('@type' in v) nodes += 1;
      props += Object.keys(v).length;
      Object.values(v).forEach(visit);
    }
  };
  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) visit(JSON.parse(m[1]));
  return { nodes, props };
}
let ldBase = { nodes: 0, props: 0 }, ldPr = { nodes: 0, props: 0 };
for (const f of baseFiles.filter((x) => x.endsWith('.html'))) {
  const b = ldCounts(read(base, f));
  ldBase.nodes += b.nodes; ldBase.props += b.props;
  if (!has(dist, f)) { if (b.nodes) fail('e', `/${f}: page with JSON-LD missing`); continue; }
  const p = ldCounts(read(dist, f));
  const homeFaqMoved = f === 'index.html' && relocated;
  const comparedBase = homeFaqMoved ? ldCounts(read(base, f), true) : b;
  const comparedPr = homeFaqMoved ? ldCounts(read(dist, f), true) : p;
  if (comparedPr.nodes < comparedBase.nodes) fail('e', `/${f}: JSON-LD nodes dropped from ${comparedBase.nodes} to ${comparedPr.nodes}`);
  if (comparedPr.props < comparedBase.props) fail('e', `/${f}: JSON-LD properties dropped from ${comparedBase.props} to ${comparedPr.props}`);
}
for (const f of walk(dist).map((x) => rel(dist, x)).filter((x) => x.endsWith('.html'))) {
  const p = ldCounts(read(dist, f));
  ldPr.nodes += p.nodes; ldPr.props += p.props;
}
report.counts.base.jsonLd = ldBase;
report.counts.pr.jsonLd = ldPr;

// (f) Homepage against the fixed 1b387c6 baseline (and against main, for anything main has added).
const homeBaseline = JSON.parse(readFileSync(path.join(root, 'scripts/home-baseline-1b387c6.json'), 'utf8'));
const homePr = has(dist, 'index.html') ? homeCounts(read(dist, 'index.html')) : null;
const homeMain = has(base, 'index.html') ? homeCounts(read(base, 'index.html')) : null;
report.home = { baseline1b387c6: homeBaseline, main: homeMain, pr: homePr };
if (!homePr) fail('f', 'homepage missing');
else if (conciseHome) {
  if (homePr.sections < 7 || homePr.sections > 8) fail('f', `concise homepage must have seven or eight sections, found ${homePr.sections}`);
  if (!relocated) fail('f', 'concise homepage requires complete verified cross-page preservation');
} else {
  for (const key of ['sections', 'headings', 'projectLinks', 'images']) {
    const floor = Math.max(homeBaseline[key], homeMain?.[key] ?? 0);
    if (homePr[key] < floor) fail('f', `homepage ${key}: ${homePr[key]}, below ${floor} (1b387c6 ${homeBaseline[key]}, main ${homeMain?.[key] ?? '-'})`);
  }
  const prSlugs = new Set(homePr.projectSlugs);
  for (const slug of new Set([...homeBaseline.projectSlugs, ...(homeMain?.projectSlugs ?? [])])) {
    // A slug that main renamed with a redirect counts under its new name.
    if (!prSlugs.has(slug) && prUrls.has(`https://www.mrwallcover.com/projects/${slug}/`)) fail('f', `homepage no longer links /projects/${slug}/`);
  }
  if (!prSlugs.has(LEE)) fail('f', 'Lee Broom is not on the homepage');
}

if (jsonOut) writeFileSync(jsonOut, JSON.stringify(report, null, 2));
console.log(`homepage: sections ${homePr?.sections}, headings ${homePr?.headings}, case studies linked ${homePr?.projectLinks}, photographs ${homePr?.images} (1b387c6: ${homeBaseline.sections}/${homeBaseline.headings}/${homeBaseline.projectLinks}/${homeBaseline.images})`);
console.log(`no-loss: pages ${report.counts.base.pages} -> ${report.counts.pr.pages}; media ${report.counts.base.mediaFiles} -> ${report.counts.pr.mediaFiles}; markdown twins ${report.counts.base.markdownTwins} -> ${report.counts.pr.markdownTwins}; JSON-LD nodes ${ldBase.nodes} -> ${ldPr.nodes}, properties ${ldBase.props} -> ${ldPr.props}`);
console.log(`projects.json: records ${report.counts.base.projectRecords} -> ${report.counts.pr.projectRecords}; gallery entries ${report.counts.base.projectGalleryEntries} -> ${report.counts.pr.projectGalleryEntries}`);
if (failures.length) {
  console.error(`NO-LOSS GUARD FAILED (${failures.length}):\n- ${failures.join('\n- ')}`);
  process.exit(1);
}
console.log('NO-LOSS GUARD PASS');
